-- ===========================================================================
-- js_test: tests/js/*_test.mjs запускает qjs из пакета quickjs-ng
-- (тот же движок, что встроен в r2d).
-- ===========================================================================
task("js_test")
    on_run(function ()
        import("core.project.project")
        local target = project.target("r2d")
        local pkg = target and target:pkg("quickjs-ng")
        if not pkg then
            raise("js_test: у цели r2d нет пакета quickjs-ng")
        end
        local qjs = path.join(pkg:installdir("bin"), is_host("windows") and "qjs.exe" or "qjs")
        if not os.isfile(qjs) then
            raise("js_test: не найден %s (xmake require quickjs-ng?)", qjs)
        end
        local files = os.files("tests/js/*_test.mjs")
        table.sort(files)
        if #files == 0 then
            raise("js_test: нет tests/js/*_test.mjs")
        end
        local failed = {}
        for _, file in ipairs(files) do
            local ok = os.execv(qjs, {file}, {try = true})
            if ok ~= 0 then
                table.insert(failed, file)
                print("FAILED %s", file)
            end
        end
        if #failed > 0 then
            raise("js_test: упало %d из %d наборов", #failed, #files)
        end
        print("js_test: %d набор(ов) прошли", #files)
    end)

