// ===========================================================================
// 2D BSP-дерево.
//
// Зачем оно в 2D-движке. Пакетная отрисовка не имеет z-буфера: порядок
// задаётся очерёдностью спрайтов в пакете. Для сеточного рейкастера глубина
// решается на каждую колонку экрана, и дерево там не нужно. Но как только
// геометрия перестаёт быть регулярной сеткой — произвольные наклонные стены,
// полигональные комнаты — нужно упорядочивать целые отрезки, и вот здесь BSP
// даёт корректный порядок «от дальних к ближним» из любой точки, без
// сортировки по расстоянию и без мерцания на пересечениях.
//
// Дерево строится один раз по статичной геометрии и потом переиспользуется
// для любой позиции наблюдателя: обход O(n), а не сортировка O(n log n).
// ===========================================================================
#pragma once

#include "r2d.h"

#include <stdbool.h>

typedef struct R2DSegment {
    float x1, y1, x2, y2;
    int   user;      // произвольная метка, которую вернул вызывающий код
    bool  split;     // true, если отрезок порождён разрезанием при построении
} R2DSegment;

typedef struct R2DBspNode {
    int splitter;    // индекс отрезка-разделителя или -1
    int front;       // индекс узла или -1
    int back;
    // Хвост, «свалившийся» в лист на предельной глубине: отрезки, которым не
    // хватило depth < R2D_BSP_MAX_DEPTH. Раньше они дублировались в общий
    // массив и становились невидимыми для обхода (order() их не отдавал),
    // хотя count()/segment() их считали.
    int leftover_first;
    int leftover_count;
} R2DBspNode;

typedef struct R2DBsp {
    R2DSegment *segments;
    int          segment_count;
    int          segment_cap;

    R2DBspNode *nodes;
    int          node_count;
    int          node_cap;
    int          root;          // -1, если дерево пустое

    int *visit_order;           // результат обхода, индексы отрезков
    int  visit_cap;
} R2DBsp;

// Строит дерево по плоскому массиву отрезков: x1,y1,x2,y2,user (stride 5).
// Возвращает false при ошибке (пустой вход, нехватка памяти).
bool r2d_bsp_build(R2DBsp *b, const float *segments, int count);
void r2d_bsp_free(R2DBsp *b);

int  r2d_bsp_segment_count(const R2DBsp *b);
int  r2d_bsp_node_count(const R2DBsp *b);
int  r2d_bsp_depth(const R2DBsp *b);

// Обход дерева из точки наблюдателя. Возвращает указатель на внутренний
// массив индексов отрезков; *out_count — сколько их.
// far_to_near == true даёт порядок рисования для пакета без z-буфера.
const int *r2d_bsp_traverse(R2DBsp *b, float x, float y, bool far_to_near, int *out_count);

