// ===========================================================================
// DSP-эффекты каналов и шин.
//
// Эффект живёт на канале (трек SDL_mixer) или на шине (группа): в обоих
// случаях это PostMix-колбэк, который получает готовый буфер в float и правит
// его на месте. Поэтому код здесь:
//
//   * не выделяет память в обработке — только чтение параметров и запись pcm;
//   * работает с любым числом каналов (декодер может отдать и 6);
//   * хранит состояние в самой структуре эффекта, а не в статике: эффектов
//     много (16 каналов + 8 шин), и у каждого своя история.
//
// Реверб — тоже эффект, но с двумя особенностями: он ленивый (буферы хвоста
// выделяются при первом включении) и работает как **посыльная шина**: сухой
// сигнал остаётся на месте, а доля `send` уходит в хвост (см. audio_reverb.c —
// там dry + wet, а не замена).
//
// Чистый C без SDL_mixer: тестируется офлайн (tests/audio/fx_test.c).
// ===========================================================================
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include <SDL3/SDL_audio.h>

#include "audio_reverb.h"

// Виды эффектов. Порядок — это и порядок в списке $.audio.effects().
typedef enum R2DAudioFxKind {
    R2D_AUDIO_FX_NONE = 0,
    R2D_AUDIO_FX_LOWPASS,
    R2D_AUDIO_FX_HIGHPASS,
    R2D_AUDIO_FX_ECHO,
    R2D_AUDIO_FX_TREMOLO,
    R2D_AUDIO_FX_BITCRUSH,
    R2D_AUDIO_FX_RINGMOD,
    R2D_AUDIO_FX_REVERB,
} R2DAudioFxKind;

// Максимальная задержка эха в кадрах (около 0,5 с на 48 кГц).
#define R2D_AUDIO_FX_FRAMES 24000

typedef struct R2DAudioFx {
    int   kind;      // R2DAudioFxKind
    float p1;        // первый параметр: срез (Гц), задержка (мс), частота, биты…
    float p2;        // второй параметр: доля повтора, глубина, коэффициент прореживания…

    // Состояние фильтров (одно на аудиоканал, максимум два).
    float z[2];      // однополюсный ФНЧ/ФВЧ
    float x1[2];     // прошлый вход — нужен ФВЧ
    // LFO для тремоло и кольцевой модуляции: фаза в долях периода.
    float phase;
    // Bitcrush: удержанный отсчёт и сколько кадров его ещё держать.
    float hold[2];
    int   hold_left;
    // Эхо: линия задержки выделяется лениво — держать её там, где эха нет,
    // незачем (это ~190 КБ на эффект).
    float *line;
    int    pos;
    // Реверб-хвост: тоже ленивый. `send` лежит в p1, `room` — в p2.
    R2DAudioReverb *reverb;
} R2DAudioFx;

/** Сколько эффектов знает движок (включая "none"). */
int r2d_audio_fx_count(void);

/** Имя эффекта по индексу; "none" — если индекс вне диапазона. */
const char *r2d_audio_fx_name(int index);

/** Имя вида эффекта (для getChannelEffect/getGroupEffect). */
const char *r2d_audio_fx_kind_name(int kind);

/**
 * Включает эффект. `rate` — частота микшера (нужна фильтрам и ревербу).
 * Возвращает false, если эффект неизвестен или не хватило памяти.
 * Состояние сбрасывается: включать эффект с хвостом от прошлого раза — сюрприз.
 */
bool r2d_audio_fx_set(R2DAudioFx *fx, int rate, const char *kind, float p1, float p2);

/**
 * Реверб-шина с полными параметрами: `send` — доля сигнала, уходящая в хвост,
 * `room` — размер помещения, `damp` — глухость, `width` — стерео-ширина.
 * Сухой сигнал остаётся на месте: это посыл, а не замена.
 */
bool r2d_audio_fx_set_reverb(R2DAudioFx *fx, int rate, float send, float room,
                             float damp, float width);

/** Обрабатывает буфер на месте. Вызывается из аудиопотока. */
void r2d_audio_fx_process(R2DAudioFx *fx, const SDL_AudioSpec *spec, float *pcm, int samples);

/** Сбрасывает состояние, не выключая эффект (пауза, повторный запуск звука). */
void r2d_audio_fx_reset(R2DAudioFx *fx);

/** Освобождает буферы (линия задержки, хвост реверба). */
void r2d_audio_fx_shutdown(R2DAudioFx *fx);
