// ===========================================================================
// Точка входа высокоуровневого API для явного импорта.
//
//   import $ from 'r2d';        // то же, что глобальный $
//   import { $ } from 'r2d';
//
// Модуль намеренно пустой по логике: API уже построен загрузчиком движка
// (r2d/bootstrap.js) и лежит в globalThis.$. Здесь он только отдаётся наружу,
// поэтому второй экземпляр $ создать невозможно.
// ===========================================================================

const api = globalThis.$;

if (!api) {
    // Такого не бывает при обычном запуске: загрузчик выполняется до точки
    // входа. Сообщение нужно, если модуль тянут в обход движка (тесты, REPL).
    throw new Error('r2d: высокоуровневое API не загружено — движок не выполнил r2d/bootstrap.js');
}

export default api;
export const $ = api;
