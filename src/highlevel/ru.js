// Русские имена высокоуровневого API: $.ru.
//
// Зачем: движок русский, документация русская, а писать игру приходилось
// латиницей — `$('<light>').radius(200).shadows(true)`. Здесь появляется
// второй, полноценный набор имён:
//
//   $('<свет>', { радиус: 260 }).в(200, 300).цвет('#ffd9a0').тени(true)
//       .конус(70).добавитьВ($.мир);
//
// Как это работает:
//   * теги — через $.aliasTag(): узел создаётся с КАНОНИЧЕСКИМ тегом, поэтому
//     отрисовка, селекторы и снимок для агента видят обычный `<light>`;
//   * методы — псевдонимы на те же функции обёртки: не копии, а ссылки, так
//     что поведение и багфиксы общие (и своих багов здесь быть не может);
//   * пространства имён — ссылки на те же объекты: `$.мир === $.world`.
//
// Латиница остаётся основным набором: русские имена — надстройка, которую
// можно не подключать (тогда таблицы просто не применяются).
//
// Контракт модуля: installRu($). Чистые таблицы экспортируются наружу — их
// проверяет qjs-тест без движка.
// ===========================================================================

