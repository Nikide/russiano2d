/**
 * Ставит русские имена: `installRu($)`.
 *
 * Порядок вызова важен: модуль дополняет уже собранное ядро, поэтому его
 * ставят последним (см. api.js). Отсутствующие теги/методы пропускаются с
 * одной записью в журнал — игра не должна падать из-за псевдонима.
 */
export function installRu($) {
    const missing = [];

    // Фабрика узлов спрашивает этот хук перед созданием узла — так русские
    // ключи атрибутов работают и в конструкторе, и в $.prefab.
    ctx.translateAttrsHook = translateAttrs;

    for (const alias of Object.keys(RU_TAGS)) {
        const canonical = RU_TAGS[alias];
        if (TAGS[canonical]) $.aliasTag(alias, canonical);
        else missing.push(`тег <${canonical}>`);
    }

    for (const alias of Object.keys(RU_METHODS)) {
        const canonical = RU_METHODS[alias];
        const fn = Wrapper.prototype[canonical];
        if (typeof fn === 'function') Wrapper.prototype[alias] = fn;
        else missing.push(`метод .${canonical}()`);
    }

    for (const alias of Object.keys(RU_NAMESPACES)) {
        const canonical = RU_NAMESPACES[alias];
        if ($[canonical] !== undefined) $[alias] = $[canonical];
        else missing.push(`$.${canonical}`);
    }

    if (missing.length) {
        $.log(`$.ru: пропущены имена без пары — ${missing.join(', ')}`);
    }
    return $;
}

/**
 * Перевод русских ключей в объекте атрибутов: `{ 'радиус': 200 }` →
 * `{ radius: 200 }`. Чистая функция: не мутирует вход, чужие ключи сохраняет.
 */
export function translateAttrs(attrs) {
    if (!attrs || typeof attrs !== 'object') return attrs;
    const out = {};
    for (const key of Object.keys(attrs)) out[RU_ATTRS[key] || key] = attrs[key];
    return out;
}
