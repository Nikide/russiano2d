// ===========================================================================
// Нативный слой движка — приватный вход модулей $.
//
// Схема движка: C → $ (а не C → engine → $). Объект `engine` с нативными
// биндингами нужен только модулям src/highlevel: bootstrap.js после установки
// $ удаляет globalThis.engine, и игровой код его больше не видит. Модули берут
// движок отсюда: `import { engine } from './native.js'` — ссылка снята в момент
// загрузки, до удаления глобального имени.
//
// В модульных тестах (qjs) движка нет: харнесс tests/js/_harness.mjs кладёт
// мок в globalThis.engine ДО импорта модулей, и он попадает сюда же.
// Игра импортировать этот модуль не может: загрузчик (src/script.c) отдаёт
// модули r2d/* только самим модулям r2d/*, игре — лишь 'r2d'.
// ===========================================================================

export let engine = globalThis.engine;

/**
 * Подмена движка в модульных тестах (tests/js): мок с нужным поведением или
 * undefined — «движка нет». Игре модуль недоступен, поэтому и подмена тоже.
 */
export function setEngineForTests(value) { engine = value; }
