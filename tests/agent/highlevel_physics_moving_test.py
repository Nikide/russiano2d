#!/usr/bin/env python3
# ===========================================================================
# §6.5. Движущиеся кинематические платформы: перенос, разворот, остановка и
# «платформа уехала».
#
# Фикстура: tests/fixtures/physics_moving/main.js. Скорость платформы задаёт
# сам тест через $.store (`liftVX`/`liftVY`), поэтому фазы воспроизводятся
# покадрово: подъём → разворот вниз → остановка → проезд по горизонтали →
# остановка → платформа падает из-под ног.
#
# Трение платформы 0.05 (как в controls_plat): перенос обязан давать
# контроллер (carryVelocity), а не трение Box2D.
#
# Проверяется:
#   * Δy наездника отслеживает Δy платформы на подъёме (перенос);
#   * после разворота наездник едет в новую сторону за ~10 кадров;
#   * через 60 кадров после остановки остаточная горизонтальная скорость ≈ 0
#     (скорость платформы не задваивается и не остаётся в теле);
#   * платформа, уехавшая вниз, не тащит наездника за собой — он падает.
#
# Горизонтальный перенос за 40 кадров уже проверен highlevel_controls_test.py;
# здесь он нужен как предусловие остаточной скорости и проверяется строже —
# без движения по горизонтали остаточную скорость мерить не на чем.
#
# Запуск:
#   python3 tests/agent/highlevel_physics_moving_test.py
# ===========================================================================

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "tools"))
from agent_client import Agent   # noqa: E402

FAILURES = []
GAME = os.path.join("tests", "fixtures", "physics_moving")

#: Полувысота тела наездника (30/2): центр стоит на верхней грани платформы.
HALF_H = 15.0


def check(condition, message):
    print(("  ok   " if condition else "  FAIL ") + message)
    if not condition:
        FAILURES.append(message)


def speed(a, vx, vy):
    """Задать скорость платформы на следующие кадры (px/с)."""
    a.eval(f"$.store.set('liftVX', {vx}); $.store.set('liftVY', {vy})")


def state(a):
    """Положение платформы и наездника, опора и скорости наездника."""
    return a.eval("""(() => {
        const n = $('#rider'), g = n.ground(), v = n.velocity();
        return {
            lx: $('#lift').pos().x, ly: $('#lift').pos().y,
            rx: n.pos().x, ry: n.pos().y,
            floor: n.onFloor() === true,
            support: g && g.node ? g.node.get(0).id : null,
            vx: v.x, vy: v.y,
        };
    })()""")


def main():
    with Agent(game=GAME, seed=11) as a:
        a.step(40)
        s0 = state(a)
        check(s0["floor"] and s0["support"] == "lift",
              f"наездник стоит на платформе (опора {s0['support']})")
        check(abs(s0["ry"] - (s0["ly"] - 10 - HALF_H)) < 2,
              f"центр наездника на верхней грани платформы "
              f"(y={s0['ry']:.1f}, ждём {s0['ly'] - 10 - HALF_H:.0f} ± 2)")

        # =====================================================================
        # 1. Подъём: платформа несёт наездника вверх.
        # =====================================================================
        speed(a, 0, -80)
        rows = []
        for _ in range(60):
            a.step(1)
            rows.append(state(a))
        up = rows[-1]
        dy_lift = up["ly"] - s0["ly"]
        dy_rider = up["ry"] - s0["ry"]
        check(dy_lift < -60,
              f"платформа действительно поднялась ({dy_lift:.1f} px за 60 кадров)")
        check(abs(dy_rider - dy_lift) < 4,
              f"наездник едет вместе с платформой (наездник {dy_rider:.1f} px, "
              f"платформа {dy_lift:.1f} px, разница {dy_rider - dy_lift:+.2f})")
        off = [i for i, r in enumerate(rows) if not r["floor"]]
        check(not off,
              f"на подъёме контакт не теряется (кадров без опоры: {len(off)})")
        check(all(abs(r["ry"] - (r["ly"] - 10 - HALF_H)) < 2 for r in rows),
              "наездник не проваливается в платформу и не висит над ней")

        # =====================================================================
        # 2. Разворот: наездник едет в новую сторону за ~10 кадров.
        # =====================================================================
        speed(a, 0, 80)
        prev = up
        flip = None
        rows = []
        for i in range(10):
            a.step(1)
            now = state(a)
            rows.append(now)
            if flip is None and now["ry"] - prev["ry"] > 0:
                flip = i + 1   # первые кадры наездник ещё летит вверх по инерции
            prev = now
        down = rows[-1]
        check(down["ly"] - up["ly"] > 4,
              f"платформа развернулась вниз (+{down['ly'] - up['ly']:.1f} px за 10 кадров)")
        check(flip is not None and flip <= 10,
              f"наездник поехал вниз за {flip} кадров после разворота (ждём ≤ 10)")
        check(abs((down["ry"] - up["ry"]) - (down["ly"] - up["ly"])) < 5,
              f"на развороте наездник остаётся на платформе "
              f"(наездник {down['ry'] - up['ry']:+.1f} px, "
              f"платформа {down['ly'] - up['ly']:+.1f} px)")
        check(all(r["floor"] for r in rows),
              "на развороте опора не теряется")

        # =====================================================================
        # 3. Остановка: остаточной скорости нет (её не задваивает).
        # =====================================================================
        speed(a, 0, 0)
        a.step(60)
        rest = state(a)
        check(abs(rest["vx"]) < 1 and abs(rest["vy"]) < 5,
              f"через 60 кадров после остановки наездник покоится "
              f"(vx={rest['vx']:.4f}, vy={rest['vy']:.4f} px/с)")
        check(rest["floor"] and rest["support"] == "lift",
              "наездник остался на остановившейся платформе")

        # =====================================================================
        # 4. Проезд по горизонтали и остановка: перенос, затем vx ≈ 0.
        # =====================================================================
        h0 = state(a)
        speed(a, 120, 0)
        a.step(40)
        h1 = state(a)
        dx_lift = h1["lx"] - h0["lx"]
        dx_rider = h1["rx"] - h0["rx"]
        check(dx_lift > 60,
              f"платформа проехала по горизонтали ({dx_lift:.1f} px за 40 кадров)")
        check(abs(dx_rider - dx_lift) < 4,
              f"наездник переносится платформой (наездник {dx_rider:.1f} px, "
              f"платформа {dx_lift:.1f} px)")
        check(h1["floor"] and h1["support"] == "lift",
              "во время проезда наездник стоит на платформе")

        speed(a, 0, 0)
        a.step(60)
        h2 = state(a)
        check(abs(h2["vx"]) < 1,
              f"через 60 кадров после остановки остаточная горизонтальная "
              f"скорость ≈ 0 (vx={h2['vx']:.4f} px/с) — скорость платформы не "
              f"задваивается и не остаётся в теле")
        check(abs(h2["rx"] - h1["rx"]) < 4,
              f"наездник не уезжает по инерции после остановки "
              f"(Δx={h2['rx'] - h1['rx']:.2f} px за 60 кадров)")
        check(h2["floor"] and h2["support"] == "lift",
              "после остановки опора по-прежнему платформа")

        # =====================================================================
        # 5. Платформа уехала вниз: наездник не приклеен, он падает.
        # =====================================================================
        d0 = state(a)
        speed(a, 0, 700)
        a.step(30)
        d1 = state(a)
        check(d1["ly"] - d0["ly"] > 250,
              f"платформа ушла вниз ({d1['ly'] - d0['ly']:.0f} px за 30 кадров)")
        check(d1["ry"] - d0["ry"] > 100,
              f"наездник падает следом, а не висит в воздухе "
              f"(Δy={d1['ry'] - d0['ry']:.0f} px)")
        check(d1["floor"] is False and d1["support"] is None,
              "опоры под наездником больше нет — контакт не «приклеен»")
        gap = d1["ry"] - (d1["ly"] - 10 - HALF_H)
        check(gap < -50,
              f"наездник отстал от уехавшей платформы (зазор {gap:.0f} px)")

        if FAILURES:
            print(a.stderr_tail(15))

    print("\nВсе проверки пройдены" if not FAILURES else f"\nПРОВАЛЕНО: {len(FAILURES)}")
    for line in FAILURES:
        print("  - " + line)
    return 1 if FAILURES else 0


if __name__ == "__main__":
    sys.exit(main())
