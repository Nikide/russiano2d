#!/usr/bin/env python3
# ===========================================================================
# Per-surface fade (roof fade): public API + CPU/GPU render evidence.
#
# A self-contained fixture game renders one authored room whose ceiling is the
# roof. The test sets world.surface(roof).fade() to 1 / 0.25 / 0 on both the CPU
# composer and the GPU backend and checks:
#   * alpha 1 is byte-identical to a world that never called fade;
#   * 0.25 and 0 change pixels (translucent pass / sorting), 0 reveals the floor;
#   * the JS wrapper validates TypeError/RangeError and the getter round-trips;
#   * draw/resource counters do not grow across frames with a fade active.
#
# Запуск: python3 tests/agent/re2d_surface_fade_test.py
# ===========================================================================
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tests', 'agent'))
from agent_client import Agent            # noqa: E402
from re2d_native_test import decode       # noqa: E402
from re2d_skip import skip_without_re2d   # noqa: E402

GAME_DIR = os.path.join(ROOT, 'build', 'test_surface_fade_game')
SCREEN = (800, 600)
TOLERANCE = 8
FAILED = []


def check(ok, message):
    print(('  ok   ' if ok else '  FAIL ') + message, flush=True)
    if not ok:
        FAILED.append(message)


def capture(a, name):
    path = os.path.join(ROOT, 'build', 'test_surface_fade_' + name + '.png')
    a.screenshot(path)
    return decode(path)


def changed_fraction(a, b):
    if (a[0], a[1]) != (b[0], b[1]):
        return 1.0
    rows0, rows1 = a[3], b[3]
    changed = total = 0
    for y in range(a[1]):
        r0, r1 = rows0[y], rows1[y]
        for x in range(0, a[0] * 4, 4):
            total += 1
            if max(abs(r0[x + c] - r1[x + c]) for c in range(3)) > TOLERANCE:
                changed += 1
    return changed / max(1, total)


def mean_luma(image, x0, y0, x1, y1):
    rows = image[3]
    total = count = 0
    for y in range(y0, y1):
        row = rows[y]
        for x in range(x0, x1):
            i = x * 4
            total += row[i] * 0.2126 + row[i + 1] * 0.7152 + row[i + 2] * 0.0722
            count += 1
    return total / max(1, count)


WORLD = {
    'version': 1,
    'cells': [
        # Roofed room: the ceiling at 96 is the roof seen from above.
        {'x': 0, 'y': 0, 'w': 200, 'h': 200, 'spans': [
            {'bottom': 0, 'top': 96, 'floorColor': '#c8c8c8', 'ceilingColor': '#303030'}
        ]},
        # Open neighbouring cell (portal keeps visibility/topology realistic).
        {'x': 200, 'y': 0, 'w': 200, 'h': 200, 'spans': [
            {'bottom': 0, 'top': 200, 'floorColor': '#a0a0a0', 'ceilingColor': '#242424'}
        ]},
    ],
    'walls': [
        {'id': 'n', 'from': [0, 0], 'to': [400, 0], 'bottom': 0, 'top': 200, 'color': '#909090'},
        {'id': 's', 'from': [0, 200], 'to': [400, 200], 'bottom': 0, 'top': 200, 'color': '#909090'},
        {'id': 'w', 'from': [0, 0], 'to': [0, 200], 'bottom': 0, 'top': 200, 'color': '#909090'},
        {'id': 'e', 'from': [400, 0], 'to': [400, 200], 'bottom': 0, 'top': 200, 'color': '#909090'},
    ],
    'portals': [
        {'id': 'room.open', 'cellA': 0, 'cellB': 1, 'from': [200, 0], 'to': [200, 200],
         'openings': [{'bottom': 0, 'top': 96}]},
    ],
}

MAIN_JS = """// Generated by tests/agent/re2d_surface_fade_test.py — roof-fade fixture.
globalThis.__fade = {
    view: { x: 100, y: 100, h: 300, yaw: 0, pitch: -89, fov: 72, near: 4 },
    world: null,
    backend: 'cpu',
    json: null,
};
$.ready(() => {
    $.world.gravity(0, 0).color('#101018');
});
$.update(() => {
    const f = globalThis.__fade;
    // The test injects the authored world JSON after startup.
    if (!f.world && f.json) {
        f.world = $.re2dWorld.fromJSON(f.json);
        f.world.backend(f.backend);
    }
});
$.render(() => {
    const f = globalThis.__fade;
    if (!f.world) return;
    f.world.backend(f.backend);
    f.world.qualityPreset('low');
    f.world.camera(f.view);
    f.world.render(f.view, 800, 600);
});
"""


def write_game():
    Path(GAME_DIR).mkdir(parents=True, exist_ok=True)
    Path(GAME_DIR, 'project.json').write_text(json.dumps({
        'title': 'Re2D surface fade fixture', 'version': '0.0.1',
        'width': SCREEN[0], 'height': SCREEN[1],
    }))
    Path(GAME_DIR, 'main.js').write_text(MAIN_JS)


def main():
    write_game()
    with Agent(game=GAME_DIR, seed=7, fixed_dt=1.0 / 60.0) as a:
        if skip_without_re2d(a, what='Re2D surface fade'):
            return 0
        a.eval('globalThis.__fade.json=' + json.dumps(json.dumps(WORLD)) + ';true')
        a.step(3)
        check(a.eval('$.debug.errors()') == [], 'fixture world has no script errors')

        surfaces = a.eval('__fade.world.info().surfaces')
        walls = a.eval('__fade.world.info().walls')
        spans = a.eval('__fade.world.info().spans')
        roof = a.eval('(()=>{for(let i=0;i<__fade.world.info().surfaces;i++){'
                      'const s=__fade.world.surface(i);'
                      'if(s&&s.kind===2&&s.cell===0)return i;}return -1;})()')
        check(walls == 6 and spans == 2 and surfaces == walls + spans * 2,
              'surface table = portal walls + 2 per span (6 walls, 2 spans, 10 surfaces)')
        check(roof >= 0 and a.eval('__fade.world.surface(%d).kind===2' % roof) is True,
              'roof resolves to the room ceiling surface (index %s)' % roof)

        # --- public API contract -------------------------------------------
        check(a.eval('__fade.world.surface(%d).fade()===1' % roof),
              'fade() defaults to 1')
        check(a.eval('(()=>{try{__fade.world.surface(%d).fade("x");return false;}'
                     'catch(e){return e instanceof TypeError;}})()' % roof),
              'non-number fade throws TypeError')
        for value in ('1.5', '-0.1', 'NaN', 'Infinity'):
            check(a.eval('(()=>{try{__fade.world.surface(%d).fade(%s);return false;}'
                         'catch(e){return e instanceof RangeError;}})()' % (roof, value)),
                  'fade(%s) throws RangeError' % value)
        check(a.eval('__fade.world.surface(99999)===null'), 'missing surface is null')
        check(a.eval('(()=>{const s=__fade.world.surface(%d);return s.fade(0.25)===s;})()' % roof),
              'fade(value) is chainable')
        check(a.eval('Math.abs(__fade.world.surface(%d).fade()-0.25)<1e-6' % roof),
              'fade() getter round-trips 0.25')
        a.eval('__fade.world.surface(%d).fade(1);__fade.backend="cpu";true' % roof)

        # --- CPU render evidence -------------------------------------------
        a.eval('__fade.world.surface(%d).fade(1);true' % roof)
        a.step(3)
        cpu1 = capture(a, 'cpu-1')
        a.eval('__fade.world.surface(%d).fade(0.25);true' % roof)
        a.step(2)
        cpu025 = capture(a, 'cpu-025')
        a.eval('__fade.world.surface(%d).fade(0);true' % roof)
        a.step(2)
        cpu0 = capture(a, 'cpu-0')
        a.eval('__fade.world.surface(%d).fade(1);true' % roof)
        a.step(2)
        cpu1b = capture(a, 'cpu-1-restored')

        check(changed_fraction(cpu1, cpu025) > 0.01,
              'CPU fade 0.25 visibly changes the frame (%.2f%%)' %
              (100.0 * changed_fraction(cpu1, cpu025)))
        check(changed_fraction(cpu025, cpu0) > 0.01,
              'CPU fade 0 vs 0.25 visibly changes the frame')
        check(changed_fraction(cpu1, cpu0) > 0.02,
              'CPU fade 0 removes the roof (%.2f%% changed)' %
              (100.0 * changed_fraction(cpu1, cpu0)))
        check(changed_fraction(cpu1, cpu1b) <= 0.001,
              'CPU fade 1 is byte-identical to a world that never called fade')
        roof_luma = mean_luma(cpu1, 300, 200, 500, 400)
        floor_luma = mean_luma(cpu0, 300, 200, 500, 400)
        check(floor_luma > roof_luma + 15.0,
              'CPU fade 0 reveals the brighter floor under the roof (roof %.1f -> floor %.1f)' %
              (roof_luma, floor_luma))

        # --- GPU render evidence -------------------------------------------
        a.eval('__fade.backend="gpu";__fade.world.surface(%d).fade(1);true' % roof)
        a.step(3)
        gpu1 = capture(a, 'gpu-1')
        a.eval('__fade.world.surface(%d).fade(0.25);true' % roof)
        a.step(2)
        gpu025 = capture(a, 'gpu-025')
        a.eval('__fade.world.surface(%d).fade(0);true' % roof)
        a.step(2)
        gpu0 = capture(a, 'gpu-0')
        check(changed_fraction(gpu1, gpu025) > 0.005,
              'GPU fade 0.25 changes the frame (transparent pass/sorting)')
        check(changed_fraction(gpu1, gpu0) > 0.01,
              'GPU fade 0 removes the roof (%.2f%% changed)' %
              (100.0 * changed_fraction(gpu1, gpu0)))
        a.eval('__fade.world.surface(%d).fade(1);true' % roof)
        a.step(2)
        gpu1b = capture(a, 'gpu-1-restored')
        check(changed_fraction(gpu1, gpu1b) <= 0.001,
              'GPU fade 1 is byte-identical to a world that never called fade')
        gpu_roof_luma = mean_luma(gpu1, 300, 200, 500, 400)
        gpu_floor_luma = mean_luma(gpu0, 300, 200, 500, 400)
        check(gpu_floor_luma > gpu_roof_luma + 10.0,
              'GPU fade 0 reveals the floor under the roof (roof %.1f -> floor %.1f)' %
              (gpu_roof_luma, gpu_floor_luma))

        # --- no per-frame resource growth with a fade active ----------------
        a.eval('__fade.world.surface(%d).fade(0.25);true' % roof)
        a.step(5)
        first = a.eval('JSON.stringify((()=>{const i=__fade.world.info();'
                       'return [i.gpuDraws,i.residentTextures,i.materials,i.surfaces];})())')
        a.step(25)
        second = a.eval('JSON.stringify((()=>{const i=__fade.world.info();'
                        'return [i.gpuDraws,i.residentTextures,i.materials,i.surfaces];})())')
        check(first == second, 'draw/resource counters stay stable across 25 frames with fade active')
        check(a.eval('$.debug.errors()') == [], 'no script errors after fade changes')
        a.eval('__fade.world.surface(%d).fade(1);__fade.backend="cpu";true' % roof)

    print()
    if FAILED:
        print('ПРОВАЛОВ: %d' % len(FAILED))
        for message in FAILED:
            print('  - ' + message)
        return 1
    print('Все проверки пройдены')
    return 0


if __name__ == '__main__':
    sys.exit(main())
