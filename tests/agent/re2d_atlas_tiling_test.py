#!/usr/bin/env python3
"""Atlas tranche: decoded-pixel path dedup and tiled atlas sets (>4096).

Generates PNGs under build/, registers flat-atlas sprites, and checks:
  * 100 sprites on one 2048x2048 PNG share ONE decoded RGBA buffer
    (decodedUniqueBytes == one image, decodedSavedBytes == 99 images, dedupHits);
  * stream byte accounting does not double-count shared pixels (sum streamBytes);
  * distinct paths stay separate;
  * a 3x2048x2048 tiled atlas set (logical 6144x2048) registers, crops a cell
    straddling the tile boundary, and CPU/GPU screenshots agree;
  * invalid tile sets / >4096 single image are typed errors;
  * configurable pinLimit (1/raise/0 unlimited/lower rejected).

Run: python3 tests/agent/re2d_atlas_tiling_test.py
"""
import json
import os
import shutil
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageChops

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "tests", "agent"))
from agent_client import Agent  # noqa: E402
from re2d_skip import skip_without_re2d  # noqa: E402

GAME = os.path.join(ROOT, "build", "atlas_tiling_game")
FAILED = []


def check(ok, message):
    print(("  ok   " if ok else "  FAIL ") + message, flush=True)
    if not ok:
        FAILED.append(message)


def atlas_png(path, width, height, seed, cells=None):
    img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    if cells:
        cols, rows, cw, ch = cells
        for row in range(rows):
            for col in range(cols):
                x0, y0 = col * cw, row * ch
                draw.rectangle([x0 + 2, y0 + 2, x0 + cw - 3, y0 + ch - 3],
                               fill=((seed * 37 + col * 11) % 256,
                                     (seed * 53 + row * 17) % 256,
                                     (seed * 71 + col * 7 + row * 5) % 256, 255))
                draw.text((x0 + cw // 2 - 6, y0 + ch // 2 - 4), f"{seed}:{col}", fill=(255, 255, 255, 255))
    else:
        draw.rectangle([0, 0, width - 1, height - 1],
                       fill=((seed * 31) % 256, (seed * 47) % 256, (seed * 61) % 256, 255))
    img.save(path)


def build_game():
    shutil.rmtree(GAME, ignore_errors=True)
    os.makedirs(GAME, exist_ok=True)
    shutil.copy(os.path.join(ROOT, "tests", "fixtures", "hello", "project.json"),
                os.path.join(GAME, "project.json"))
    # Minimal, non-animated host: the 2D world must not draw moving nodes between
    # the CPU and GPU screenshots (hello's goblins would make the parity diff
    # meaningless).
    Path(os.path.join(GAME, "main.js")).write_text(
        "// generated by tests/agent/re2d_atlas_tiling_test.py\n"
        "$.ready(() => { $.world.color('#101820'); });\n")
    atlas_png(os.path.join(GAME, "shared_2048.png"), 2048, 2048, 3,
              cells=(4, 4, 512, 512))
    atlas_png(os.path.join(GAME, "other_256.png"), 256, 256, 7)
    # 3x2048 x 2048 logical sheet: a 300px cell straddles x=2048/4096. Tiles are
    # solid colours so CPU/GPU sampling parity is exact (no glyph/edge filtering).
    for i in range(3):
        atlas_png(os.path.join(GAME, f"tile_{i}.png"), 2048, 2048, 10 + i)
    atlas_png(os.path.join(GAME, "too_big_4097.png"), 4097, 8, 1)


def world_js():
    return r'''(() => {
        const data = {version: 1, cells: [
            {x: 0, y: 0, w: 12288, h: 8192, spans: [
                {bottom: 0, top: 160, floorColor: '#334455', ceilingColor: '#223344'}]}
        ], walls: [], portals: []};
        const w = $.re2dWorld.fromJSON(JSON.stringify(data));
        globalThis.world = w;
        w.backend('gpu');
        w.renderQuality('high');
        globalThis.__view = {x: 4096, y: 4096, h: 2400, mode: 'topdown',
            orthoHeight: 3200, yaw: 0, pitch: -89.99, fov: 55, near: 1};
        w.render({...__view}, 640, 360);
        globalThis.__nodes = [];
        return JSON.stringify({ok: true});
    })()'''


def register_shared_js(count):
    return r'''(() => {
        for (let i = 0; i < %d; i++) {
            const node = $('<sprite>', {id: 'shared_' + i})
                .at(3600 + (i %% 10) * 60, 3600 + Math.floor(i / 10) * 60)
                .depth(0).size(48, 48).hide().appendTo($.world);
            world.sprite(node, {atlas: 'shared_2048.png', columns: 4, rows: 4,
                directions: 1, mirror: false, cell: {w: 512, h: 512}, pivot: 'feet',
                width: 48, height: 48, blend: 'masked'});
            __nodes.push(node);
        }
        const other = $('<sprite>', {id: 'other'}).at(4800, 4600).depth(0)
            .size(48, 48).hide().appendTo($.world);
        world.sprite(other, {atlas: 'other_256.png', columns: 1, rows: 1,
            directions: 1, mirror: false, cell: {w: 256, h: 256}, pivot: 'feet',
            width: 48, height: 48, blend: 'masked'});
        // Same decoded PNG, different grid/cell metadata: pixels are shared but
        // each registration keeps its own grid.
        for (let i = 0; i < 2; i++) {
            const node = $('<sprite>', {id: 'shared_grid_' + i})
                .at(5000 + i * 80, 3600).depth(0).size(64, 64).hide().appendTo($.world);
            world.sprite(node, {atlas: 'shared_2048.png', columns: 8, rows: 2,
                directions: 1, mirror: false, cell: {w: 256, h: 1024}, pivot: 'center',
                width: 64, height: 64, blend: 'masked'});
            __nodes.push(node);
        }
        return JSON.stringify({sprites: __nodes.length});
    })()''' % count


def render_frames(count):
    return r'''(() => {
        const out = [];
        for (let i = 0; i < %d; i++) {
            world.render({...__view}, 640, 360);
            const info = world.info();
            out.push({blocked: info.visibleAtlasBlocked, draws: info.gpuDrawsActor,
                      visible: info.visibleAtlasSprites,
                      suppressed: info.groundShadowsSuppressed});
        }
        return JSON.stringify(out);
    })()''' % count


def info(a):
    return json.loads(a.eval("JSON.stringify(world.info())") or "{}")


def stream_info(a):
    return json.loads(a.eval("JSON.stringify(world.streamInfo())") or "{}")


def errors(a):
    return json.loads(a.eval("JSON.stringify($.debug.errors())") or "[]")


def main():
    build_game()
    with Agent(game=GAME, seed=17, fixed_dt=1.0 / 60.0) as a:
        if skip_without_re2d(a):
            return 0
        a.step(2)
        json.loads(a.eval(world_js()))

        # --- A) decoded-pixel dedup: 100 registrations, one 2048x2048 PNG -----
        json.loads(a.eval(register_shared_js(100)))
        a.eval("world.streamConfig({residentBytes: 0, residentItems: 0, "
               "uploadBytes: 0, uploadItems: 0, promoteItems: 0})")
        warm = json.loads(a.eval(render_frames(6)))
        check(all(f.get("blocked", 0) == 0 for f in warm),
              "dedup world has no blocked visible atlases after warm")
        si = stream_info(a)
        image_bytes = 2048 * 2048 * 4
        other_bytes = 256 * 256 * 4
        check(si.get("decodedUniqueBytes") == image_bytes + other_bytes,
              "decodedUniqueBytes counts one buffer per unique path: %s"
              % si.get("decodedUniqueBytes"))
        check(si.get("decodedSavedBytes") >= 99 * image_bytes,
              "decodedSavedBytes reports dedup savings: %s"
              % si.get("decodedSavedBytes"))
        check(si.get("dedupHits", 0) >= 99,
              "dedupHits counts shared registrations: %s" % si.get("dedupHits"))
        atlases = si.get("atlases") or []
        shared = [e for e in atlases if e.get("path") == "shared_2048.png"]
        other = [e for e in atlases if e.get("path") == "other_256.png"]
        check(len(shared) == 102,
              "100 shared registrations + 2 rebind-different-grid registrations kept")
        check(all(e.get("sharedRefs") == 102 for e in shared),
              "sharedRefs reports 102 references per shared atlas")
        check(len({(e.get("columns"), e.get("rows"), e.get("cellW"), e.get("cellH"))
                   for e in shared}) > 1,
              "different grid/cell metadata shares the same decoded image")
        check(len(other) == 1 and other[0].get("sharedRefs") == 1,
              "distinct path stays a separate image")
        # Stream accounting: unique image bytes counted once across aliases.
        stream_sum = sum(e.get("streamBytes", 0) for e in shared)
        check(stream_sum == image_bytes,
              "shared pixels counted once in stream accounting: %s" % stream_sum)
        check(si.get("residentBytes", 0) >= image_bytes + other_bytes,
              "residentBytes includes the unique decoded bytes")
        check(si.get("residentBytes", 0) <= image_bytes + other_bytes + 4 * 1024 * 1024,
              "residentBytes does not double-count shared pixels: %s"
              % si.get("residentBytes"))
        check(not [e for e in errors(a) if e.get("code") == "R2D_ATLAS_NOT_RESIDENT"],
              "dedup registration produced no atlas-residency errors")

        # --- B) tiled atlas set: 3 x 2048x2048 = logical 6144x2048 -----------
        tiled_setup = a.eval(r'''(() => {
            const node = $('<sprite>', {id: 'tiled'}).at(3600, 3000).depth(0)
                .size(300, 300).hide().appendTo($.world);
            world.sprite(node, {
                atlas: {files: ['tile_0.png', 'tile_1.png', 'tile_2.png'],
                        tile: {width: 2048, height: 2048, columns: 3, rows: 1}},
                columns: 20, rows: 1, directions: 1,
                cell: {w: 300, h: 300}, pivot: 'feet',
                width: 300, height: 300, blend: 'masked'});
            globalThis.__tiled = node;
            // Cell 6 starts at logical x=1800 and ends at 2100: it straddles the
            // tile_0/tile_1 boundary at x=2048.
            __tiled.get(0).sprite_col = 6;
            return JSON.stringify({registered: world.info().atlasSprites});
        })()''')
        check(json.loads(tiled_setup).get("registered") == 104,
              "tiled atlas set registered")
        tiled_frames = json.loads(a.eval(render_frames(4)))
        check(all(f.get("blocked", 0) == 0 for f in tiled_frames),
              "tiled atlas set is resident and visible without blocking")
        tiled_errors = [e for e in errors(a) if "tiled" in json.dumps(e)]
        check(not tiled_errors, "tiled atlas registration has no errors")
        si = stream_info(a)
        tiled = [e for e in si.get("atlases", []) if e.get("tileCount") == 3]
        check(len(tiled) == 1, "streamInfo reports the tiled registration")
        if tiled:
            entry = tiled[0]
            check(entry.get("imageW") == 6144 and entry.get("imageH") == 2048,
                  "logical tiled sheet dimensions 6144x2048: %sx%s"
                  % (entry.get("imageW"), entry.get("imageH")))
            check(entry.get("path") == "tile_0.png+tile_1.png+tile_2.png",
                  "tiled path reported as the joined tile list: %s" % entry.get("path"))
            check(len(entry.get("tiles") or []) == 3,
                  "streamInfo exposes the tile path list")

        # CPU/GPU parity for the boundary-straddling cell.
        a.eval("world.backend('cpu')")
        json.loads(a.eval(render_frames(2)))
        a.screenshot(os.path.join(ROOT, "build", "atlas_tiling_cpu.png"))
        a.eval("world.backend('gpu')")
        json.loads(a.eval(render_frames(2)))
        a.screenshot(os.path.join(ROOT, "build", "atlas_tiling_gpu.png"))
        cpu = Image.open(os.path.join(ROOT, "build", "atlas_tiling_cpu.png")).convert("RGB")
        gpu = Image.open(os.path.join(ROOT, "build", "atlas_tiling_gpu.png")).convert("RGB")
        diff = ImageChops.difference(cpu, gpu)
        changed = sum(1 for pixel in diff.getdata() if max(pixel) > 2)
        # Per-pixel CPU/GPU atlas edge sampling can differ by ~1px (scissor
        # rounding), so compare the CELL CONTENT strictly and allow only border
        # jaggies: the tiled stripes must be identical away from the silhouette
        # edge. A different cell/tile choice would differ across the whole body.
        light = cpu.point(lambda value: 255 if value > 24 else 0).convert("L")
        bbox = light.getbbox()
        inner_changed = -1
        if bbox:
            x0, y0, x1, y1 = bbox
            box = (x0 + 4, y0 + 4, max(x0 + 5, x1 - 4), max(y0 + 5, y1 - 4))
            inner = diff.crop(box)
            inner_changed = sum(1 for pixel in inner.getdata() if max(pixel) > 2)
        check(changed <= 400 and inner_changed == 0,
              "CPU and GPU agree on the tiled boundary cell content "
              "(edge-only diffs %d, inner %s)" % (changed, inner_changed))

        # --- C) validation: ragged/wrong/dimension errors --------------------
        def expect_error(code, label):
            result = a.eval(r'''(() => {
                try { %s; return 'no-error'; }
                catch (e) { return (e && e.name) + ':' + (e && e.message); }
            })()''' % code)
            check("no-error" not in result, "%s rejected: %s" % (label, str(result)[:90]))

        expect_error(r'''world.sprite($('<sprite>', {id:'bad1'}).at(0,0).size(32,32)
            .hide().appendTo($.world), {atlas:{files:['tile_0.png','tile_1.png'],
            tile:{width:2048,height:2048,columns:3,rows:1}}, columns:1, rows:1,
            directions:1, cell:{w:128,h:128}, pivot:'feet', width:32, height:32})''',
            "ragged tile set")
        expect_error(r'''world.sprite($('<sprite>', {id:'bad2'}).at(0,0).size(32,32)
            .hide().appendTo($.world), {atlas:{files:['tile_0.png','other_256.png'],
            tile:{width:2048,height:2048,columns:2,rows:1}}, columns:1, rows:1,
            directions:1, cell:{w:128,h:128}, pivot:'feet', width:32, height:32})''',
            "tile PNG with wrong dimensions")
        expect_error(r'''world.sprite($('<sprite>', {id:'bad3'}).at(0,0).size(32,32)
            .hide().appendTo($.world), {atlas:'too_big_4097.png', columns:1, rows:1,
            directions:1, cell:{w:128,h:128}, pivot:'feet', width:32, height:32})''',
            "single-image atlas above 4096")

        # --- D) hot reload bumps the cache generation without freeing live
        # images: registered actors keep rendering and unique bytes stay stable.
        unique_before = stream_info(a).get("decodedUniqueBytes")
        reload_result = a.eval(r'''(() => {
            try {
                world.reloadJSON(JSON.stringify({version: 1, cells: [
                    {x: 0, y: 0, w: 12288, h: 8192, spans: [
                        {bottom: 0, top: 160, floorColor: '#334455', ceilingColor: '#223344'}]}
                ], walls: [], portals: []}));
                return 'ok';
            } catch (e) { return 'error:' + (e && e.message); }
        })()''')
        check(reload_result == "ok", "world reloadJSON succeeds with live atlas actors: %s"
              % str(reload_result)[:80])
        reload_frames = json.loads(a.eval(render_frames(4)))
        check(all(f.get("blocked", 0) == 0 for f in reload_frames),
              "reload keeps visible atlases resident")
        check(stream_info(a).get("decodedUniqueBytes") == unique_before,
              "reload keeps live decoded images (generation bump only)")

        # --- E) configurable sticky pin limit --------------------------------
        limit = stream_info(a).get("pinLimit")
        check(limit == 64, "default pinLimit is 64: %s" % limit)
        a.eval("world.streamConfig({pinLimit: 1})")
        check(stream_info(a).get("pinLimit") == 1, "pinLimit lowered to 1")
        result = a.eval(r'''(() => {
            try {
                world.atlasPin('tile_0.png', true);   // pending 1 (ok)
                world.atlasPin('tile_1.png', true);   // second pending -> overflow
                return 'no-error';
            } catch (e) { return (e && e.name) + ':' + (e && e.message); }
        })()''')
        check("RangeError" in result, "pin overflow above limit is a RangeError: %s" % str(result)[:80])
        result = a.eval(r'''(() => {
            try { world.streamConfig({pinLimit: 0}); return 'ok'; }
            catch (e) { return 'error:' + e.message; }
        })()''')
        check(result == "ok", "pinLimit 0 = unlimited accepted")
        a.eval("world.atlasPin('tile_2.png', true); world.atlasPin('other_256.png', true)")
        check(stream_info(a).get("pinsPending") >= 3,
              "unlimited pending pins accumulate: %s" % stream_info(a).get("pinsPending"))
        result = a.eval(r'''(() => {
            try { world.streamConfig({pinLimit: 1}); return 'no-error'; }
            catch (e) { return (e && e.name) + ':' + (e && e.message); }
        })()''')
        check("RangeError" in result,
              "lowering pinLimit below pending pins is rejected, not silently dropped: %s"
              % str(result)[:80])
        check(stream_info(a).get("pinsPending") >= 3,
              "rejected lower limit keeps pending pins")

    print()
    if FAILED:
        print("FAILURES: %d" % len(FAILED))
        for message in FAILED:
            print("  - " + message)
        return 1
    print("All atlas dedup/tiling/pin-limit checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
