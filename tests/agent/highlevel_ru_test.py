#!/usr/bin/env python3
# ===========================================================================
# Тест русских имён API ($.ru).
#
# Проверяем, что «второй набор имён» — не косметика: узел с русским тегом
# получает канонический тег (иначе его не увидят отрисовка, селекторы и снимок
# для агента), русские атрибуты доходят до подсистем, методы-псевдонимы ведут
# себя как оригиналы, а пространства имён — те же объекты.
#
# Запуск (после сборки):
#   python3 tests/agent/highlevel_ru_test.py
# ===========================================================================

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "tools"))
from agent_client import Agent   # noqa: E402

FAILURES = []
GAME = os.path.join("tests", "fixtures", "ru")


def check(condition, message):
    print(("  ok   " if condition else "  FAIL ") + message)
    if not condition:
        FAILURES.append(message)


def main():
    with Agent(game=GAME, seed=7) as a:
        # --- Каждый русский тег резолвится в свой канонический ---------------
        # Часть тегов объявляют подсистемы (layers, tilemap, particles,
        # widgets), поэтому проверить всю таблицу можно только в живом движке.
        tags = [
            ("игрок", "player"), ("враг", "enemy"), ("нпс", "npc"),
            ("предмет", "pickup"), ("пуля", "bullet"), ("спрайт", "sprite"),
            ("прямоугольник", "rect"), ("круг", "circle"), ("текст", "text"),
            ("тайлмап", "tilemap"), ("свет", "light"), ("светплощадка", "lightarea"),
            ("частицы", "particles"), ("туман", "fog"), ("слой", "layer"),
            ("зона", "trigger"), ("область", "area"), ("стена", "wall"),
            ("панель", "ui.panel"), ("надпись", "ui.label"), ("кнопка", "ui.button"),
            ("полоса", "ui.bar"), ("картинка", "ui.image"), ("строка", "ui.row"),
            ("колонка", "ui.col"), ("сетка", "ui.grid"), ("прокрутка", "ui.scroll"),
            ("флажок", "ui.checkbox"), ("ползунок", "ui.slider"), ("поле", "ui.input"),
            ("список", "ui.list"), ("диалог", "ui.dialog"),
        ]
        wrong = []
        for ru, canonical in tags:
            # Узел создаём и сразу убираем: он попадает в мир, а следующие
            # проверки считают узлы селекторами (иначе счёт поедет).
            got = a.eval("(function () { var n = $('<%s>'); var t = n.nodes[0].tag;"
                         " n.remove(); return t; })()" % ru)
            if got != canonical:
                wrong.append("%s→%s (получилось %s)" % (ru, canonical, got))
        check(not wrong, "все %d русских тегов дают канонический тег%s"
              % (len(tags), "" if not wrong else ": " + ", ".join(wrong)))

        # --- Теги: русское имя, канонический тег -----------------------------
        check(a.eval("$('#фонарь').nodes[0].tag") == "light",
              "узел <свет> создан с каноническим тегом light")
        check(a.eval("$('#фон').nodes[0].tag") == "rect",
              "узел <прямоугольник> — это rect")
        check(a.eval("$('#герой').nodes[0].tag") == "player",
              "узел <игрок> — это player")
        check(a.eval("$('#дымка').nodes[0].tag") == "fog",
              "узел <туман> — это fog")

        # --- Селекторы по-русски находят те же узлы --------------------------
        check(a.eval("$('свет').nodes.length") == 1, "$('свет') находит узел света")
        check(a.eval("$('свет').nodes[0].id") == "фонарь", "это тот же узел")
        check(a.eval("$('игрок').nodes.length") == 1, "$('игрок') находит игрока")
        check(a.eval("$('#герой.нет').nodes.length") == 0,
              "русское слово в селекторе не ломает поиск по id")

        # --- Русские атрибуты дошли до подсистем ------------------------------
        check(a.eval("$('#фонарь').radius()") == 260, "атрибут 'радиус' стал radius")
        check(a.eval("$('#фонарь').intensity()") == 1, "атрибут 'яркость' стал intensity")
        check(a.eval("$('#фонарь').shadows()") is True, "атрибут 'тени' стал shadows")
        check(a.eval("$('#дымка').nodes[0].attrs.density") == 0.3,
              "атрибут 'плотность' стал density")
        check(a.eval("$('#герой').nodes[0].attrs.speed") == 220,
              "атрибут 'скорость' стал speed")

        # --- Методы-псевдонимы ведут себя как оригиналы -----------------------
        # $.fn — это Wrapper.prototype, поэтому метод виден и там, и у узла,
        # и это ровно та же функция, а не копия.
        check(a.eval("typeof $('#фон').в") == "function", "метод .в() есть у обёртки")
        check(a.eval("$('#фон').в === $('#фон').at"), ".в() — та же функция, что .at()")
        a.eval("$('#фон').в(123, 456)")
        check(a.eval("$('#фон').позиция().x") == 123 and a.eval("$('#фон').позиция().y") == 456,
              ".в(x, y) перемещает узел")
        a.eval("$('#фон').в(400, 300)")
        check(a.eval("$('#фон').цвет === $('#фон').color"), ".цвет() — та же функция, что .color()")
        a.eval("$('#фон').цвет('#ff0000')")
        check(a.eval("$('#фон').nodes[0].color") == a.eval("$.gfx.rgba(255, 0, 0, 255)"),
              ".цвет('#ff0000') покрасил узел")
        check(a.eval("$('#герой').скорость()") == 220, ".скорость() читает скорость")
        a.eval("$('#герой').скорость(180)")
        check(a.eval("$('#герой').speed()") == 180, ".скорость(180) пишет ту же скорость")
        a.eval("$('#фон').скрыть()")
        check(a.eval("$('#фон').isVisible()") is False, ".скрыть() скрывает узел")
        a.eval("$('#фон').показать()")
        check(a.eval("$('#фон').isVisible()") is True, ".показать() показывает обратно")

        # --- Пространства имён — те же объекты --------------------------------
        check(a.eval("$.мир === $.world"), "$.мир — это $.world")
        check(a.eval("$.графика === $.gfx"), "$.графика — это $.gfx")
        check(a.eval("$.сцена === $.scene"), "$.сцена — это $.scene")
        check(a.eval("$.переводы === $.tr"), "$.переводы — это $.tr")

        # --- Подписка по-русски ------------------------------------------------
        a.eval("$.ru_счёт = 0; $('#фон').на('проверка', function () { $.ru_счёт++; })")
        a.eval("$('#фон').испустить('проверка')")
        check(a.eval("$.ru_счёт") == 1, "подписка .на() и вызов .испустить() работают")

        # --- Кадр с русской сценой рисуется ------------------------------------
        a.step(3)
        check(a.eval("engine.frame") > 0, "кадры идут")
        check(a.eval("$.gfx.light.count()") >= 0, "свет подсистемы жив")

    print("Все проверки пройдены" if not FAILURES else "ПРОВАЛЕНО: %d" % len(FAILURES))
    return 1 if FAILURES else 0


if __name__ == "__main__":
    sys.exit(main())
