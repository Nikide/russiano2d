#!/usr/bin/env python3
"""Deterministic async atlas PNG prefetch (world.atlasPrefetch*).

Generates a game with several distinct atlas PNGs under build/ and renders the
same static + moving-camera scenes in separate engine runs:

  * control run: prefetch OFF (default);
  * prefetch run: world.atlasAsync(true), prefetch all PNGs, wait for READY,
    then register the same sprites.

The contract under test: prefetch only removes synchronous FILE READS. It must
never change pixels, counters or warnings, and if bytes are not READY the
registration falls back to the normal synchronous read with identical output.

Checks:
  * screenshots (static 5 frames and 120 moving-camera frames) are byte-identical
    between control and prefetch runs;
  * enabling prefetch but prefetching nothing still falls back and is identical;
  * prefetch -> wait READY -> register -> `consumed` accounting (ready -> 0);
  * missing file: token is returned, info reports `failed` with an error, the
    sprite registration fails with the same typed error as the control run;
  * corrupt PNG: prefetched bytes are READY, decode fails on the main thread and
    falls back to the same synchronous error (never a silently wrong image);
  * clear cancels/drops state and keeps working; disable stops the worker
    (`workers == 0`) and makes atlasPrefetch return 0;
  * reloadJSON (hot reload) keeps the live atlas registration deterministic;
  * registration time (control vs prefetch) and read bytes are reported as the
    honest sync-read saving (decode/GPU work is unchanged and not claimed).

Run: python3 tests/agent/re2d_atlas_prefetch_test.py
"""
import json
import os
import random
import shutil
import sys
import time

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "tests", "agent"))
from agent_client import Agent  # noqa: E402
from re2d_skip import skip_without_re2d  # noqa: E402

GAME = os.path.join(ROOT, "build", "atlas_prefetch_game")
ATLAS_COUNT = 8
FAILED = []


def check(ok, message):
    print(("  ok   " if ok else "  FAIL ") + message, flush=True)
    if not ok:
        FAILED.append(message)


def atlas_png(path, width, height, seed, cells):
    # Deterministic pseudo-noise: the files are large enough that the avoided
    # synchronous read is measurable, and identical across the two runs.
    data = random.Random(1000 + seed).randbytes(width * height * 4)
    img = Image.frombytes("RGBA", (width, height), data)
    draw = ImageDraw.Draw(img)
    cols, rows, cw, ch = cells
    for row in range(rows):
        for col in range(cols):
            x0, y0 = col * cw, row * ch
            draw.rectangle([x0, y0, x0 + cw - 1, y0 + ch - 1], outline=(255, 255, 255, 255))
            draw.text((x0 + 4, y0 + 4), "%d:%d" % (seed, col), fill=(255, 255, 255, 255))
    img.save(path)


def build_game():
    shutil.rmtree(GAME, ignore_errors=True)
    os.makedirs(GAME, exist_ok=True)
    shutil.copy(os.path.join(ROOT, "tests", "fixtures", "hello", "project.json"),
                os.path.join(GAME, "project.json"))
    with open(os.path.join(GAME, "main.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tests/agent/re2d_atlas_prefetch_test.py\n"
                "$.ready(() => { $.world.gravity(0, 0).color('#101820'); });\n")
    for i in range(ATLAS_COUNT):
        # 1024x1024, 4x2 cells of 256x512: big enough that the sync read is
        # measurable, small enough for a fast test.
        atlas_png(os.path.join(GAME, "atlas_%d.png" % i), 1024, 1024, 3 + i,
                  cells=(4, 2, 256, 512))
    with open(os.path.join(GAME, "corrupt.png"), "wb") as f:
        f.write(b"this is not a png\n" * 64)


WORLD_JSON = ('{"version":1,"cells":[{"x":0,"y":0,"w":4096,"h":2048,'
              '"spans":[{"bottom":0,"top":160,"floorColor":"#334455",'
              '"ceilingColor":"#223344"}]}],"walls":[],"portals":[]}')
WORLD_JS = r'''(() => {
    globalThis.world = $.re2dWorld.fromJSON(%s);
    world.backend('gpu');
    world.renderQuality('low');
    globalThis.__view = {x: 400, y: 1024, h: 48, yaw: 0, pitch: 0, fov: 80, near: 1};
    globalThis.__nodes = [];
    world.render({...__view}, 480, 270);
    return JSON.stringify({atlasSprites: world.info().atlasSprites});
})()''' % json.dumps(WORLD_JSON)

REGISTER_JS = r'''(() => {
    const t0 = $.now();
    for (let i = 0; i < %d; i++) {
        const node = $('<sprite>', {id: 'pf_' + i})
            .at(700 + i * 220, 900 + (i %% 2) * 260).depth(0).size(96, 96)
            .hide().appendTo($.world);
        world.sprite(node, {atlas: 'atlas_' + i + '.png', columns: 4, rows: 2,
            directions: 4, cell: {w: 256, h: 512}, pivot: 'feet',
            width: 96, height: 96, blend: 'masked'});
        __nodes.push(node);
    }
    return JSON.stringify({ms: $.now() - t0, sprites: __nodes.length});
})()''' % ATLAS_COUNT

STATIC_FRAMES_JS = r'''(() => {
    for (let f = 0; f < 5; f++) world.render({...__view}, 480, 270);
    return JSON.stringify(world.info());
})()'''

MOVING_FRAMES_JS = r'''(() => {
    for (let f = 0; f < 120; f++) {
        __view.x = 400 + f * 3;
        __view.y = 1024 + Math.sin(f * 0.08) * 180;
        __view.yaw = 8 * Math.sin(f * 0.05);
        world.render({...__view}, 480, 270);
    }
    return JSON.stringify(world.info());
})()'''


def screenshot(a, name):
    path = os.path.join(ROOT, "build", "atlas_prefetch_" + name + ".png")
    a.screenshot(path)
    with Image.open(path) as img:
        return img.convert("RGBA").tobytes()


def info(a):
    return json.loads(a.eval("JSON.stringify(world.atlasPrefetchInfo())") or "{}")


def world_info(a):
    return json.loads(a.eval("JSON.stringify(world.info())") or "{}")


def caught(a, expression):
    return a.eval("(()=>{try{%s;return 'no-error';}catch(e){"
                  "return (e&&e.name)+':'+(e&&e.message);}})()" % expression)


def wait_ready(a, expected, timeout=10.0):
    end = time.time() + timeout
    while time.time() < end:
        state = info(a)
        if state.get("ready", 0) + state.get("failed", 0) >= expected:
            return state
        time.sleep(0.01)
    return info(a)


def register_conflict_error(a, path):
    return caught(a, r'''(() => {
        const node = $('<sprite>', {id: 'bad_' + Math.random()})
            .at(800, 800).depth(0).size(64, 64).hide().appendTo($.world);
        world.sprite(node, {atlas: '%s', columns: 1, rows: 1, directions: 1,
            cell: {w: 64, h: 64}, pivot: 'feet', width: 64, height: 64});
        node.remove();
    })()''' % path)


def run_control():
    with Agent(game=GAME, seed=21, fixed_dt=1.0 / 60.0) as a:
        if skip_without_re2d(a):
            return None
        a.step(2)
        json.loads(a.eval(WORLD_JS))
        t0 = time.perf_counter()
        reg = json.loads(a.eval(REGISTER_JS))
        register_wall_ms = (time.perf_counter() - t0) * 1000.0
        static_info = json.loads(a.eval(STATIC_FRAMES_JS))
        static_pixels = screenshot(a, "control_static")
        moving_info = json.loads(a.eval(MOVING_FRAMES_JS))
        moving_pixels = screenshot(a, "control_moving")
        errors = {}
        errors["missing"] = register_conflict_error(a, "missing.png")
        errors["corrupt"] = register_conflict_error(a, "corrupt.png")
        prefetch_info = info(a)
        check(prefetch_info.get("enabled") is False, "prefetch is OFF by default")
        check(prefetch_info.get("workers") == 0, "no worker thread before first prefetch")
        check(a.eval("world.atlasAsync()") is False, "atlasAsync() getter reports OFF")
        check(a.eval("world.atlasPrefetch('atlas_0.png')") == 0,
              "atlasPrefetch returns 0 while prefetch is disabled")
        return {
            "register_ms": register_wall_ms, "static": static_pixels, "moving": moving_pixels,
            "static_info": static_info, "moving_info": moving_info, "errors": errors,
        }


def run_prefetch():
    with Agent(game=GAME, seed=21, fixed_dt=1.0 / 60.0) as a:
        if skip_without_re2d(a):
            return None
        a.step(2)
        json.loads(a.eval(WORLD_JS))
        check(a.eval("world.atlasAsync(true)") is True, "atlasAsync(true) enables prefetch")
        tokens = json.loads(a.eval(
            "JSON.stringify(Array.from({length:%d},(_,i)=>"
            "world.atlasPrefetch('atlas_'+i+'.png')))" % ATLAS_COUNT))
        check(all(isinstance(t, int) and t > 0 for t in tokens),
              "atlasPrefetch returns positive tokens: %s" % (tokens,))
        check(len(set(tokens)) == ATLAS_COUNT, "every prefetch got a distinct token")
        # Duplicate request of an already pending/ready path -> 0 ("already").
        check(a.eval("world.atlasPrefetch('atlas_0.png')") == 0,
              "duplicate prefetch returns 0")
        pending = info(a)
        check(pending.get("workers") == 1, "worker thread is running")
        check(pending.get("enabled") is True, "info reports enabled")
        check(pending.get("requested", 0) == ATLAS_COUNT,
              "requested counter %s" % pending.get("requested"))
        check(pending.get("bytesPending", 0) > 0 or pending.get("ready", 0) > 0,
              "byte accounting is visible while loading")
        ready = wait_ready(a, ATLAS_COUNT)
        check(ready.get("ready") == ATLAS_COUNT and ready.get("failed") == 0,
              "all %d prefetched PNGs are READY: %s" % (ATLAS_COUNT, ready.get("ready")))
        check(ready.get("bytesReady", 0) > 0, "bytesReady > 0 before registration")
        for entry in ready.get("paths") or []:
            check(entry.get("state") == "ready", "path %s is ready" % entry.get("path"))

        t0 = time.perf_counter()
        reg = json.loads(a.eval(REGISTER_JS))
        register_wall_ms = (time.perf_counter() - t0) * 1000.0
        after = info(a)
        check(after.get("consumed") == ATLAS_COUNT,
              "registration consumed all prefetched entries: %s" % after.get("consumed"))
        check(after.get("ready") == 0 and after.get("bytesReady") == 0,
              "ready cache and bytes are empty after registration")
        for entry in after.get("paths") or []:
            check(entry.get("state") == "consumed",
                  "path %s is consumed" % entry.get("path"))

        static_info = json.loads(a.eval(STATIC_FRAMES_JS))
        static_pixels = screenshot(a, "prefetch_static")
        moving_info = json.loads(a.eval(MOVING_FRAMES_JS))
        moving_pixels = screenshot(a, "prefetch_moving")

        # Hot reload keeps the live atlas registration deterministic.
        a.eval("world.reloadJSON(%s)" % json.dumps(WORLD_JSON))
        a.eval("world.render({...__view}, 480, 270)")
        reload_pixels = screenshot(a, "prefetch_reload")

        # Missing/corrupt fallbacks: same typed error as the control run.
        pre_missing = a.eval("world.atlasPrefetch('missing.png')")
        check(isinstance(pre_missing, int) and pre_missing > 0,
              "prefetch of a missing file returns a token (no throw)")
        pre_corrupt = a.eval("world.atlasPrefetch('corrupt.png')")
        check(isinstance(pre_corrupt, int) and pre_corrupt > 0,
              "prefetch of a corrupt file returns a token")
        ready = wait_ready(a, 2)
        states = {e["path"]: e for e in ready.get("paths") or []}
        check(states.get("missing.png", {}).get("state") == "failed",
              "missing prefetch is reported as failed")
        check(bool(states.get("missing.png", {}).get("error")),
              "missing prefetch carries an error text")
        check(states.get("corrupt.png", {}).get("state") == "ready",
              "corrupt bytes are prefetched (decode is a main-thread concern)")
        errors = {}
        errors["missing"] = register_conflict_error(a, "missing.png")
        errors["corrupt"] = register_conflict_error(a, "corrupt.png")

        # Clear/drop and keep working.
        a.eval("world.atlasPrefetchClear()")
        cleared = info(a)
        check(cleared.get("entries") == 0 and cleared.get("pending") == 0 and
              cleared.get("ready") == 0 and cleared.get("bytesReady") == 0,
              "clear drops all prefetch state")
        check(cleared.get("enabled") is True and cleared.get("workers") == 1,
              "clear keeps the module usable (worker idle)")
        again = a.eval("world.atlasPrefetch('atlas_0.png')")
        check(isinstance(again, int) and again > 0, "prefetch works after clear")
        again1 = a.eval("world.atlasPrefetch('atlas_1.png')")
        check(isinstance(again1, int) and again1 > 0, "second path prefetched after clear")
        wait_ready(a, 2)
        # Tiled atlas sets check every tile path through the same PNG loader.
        tiled = a.eval(r'''(() => {
            const node = $('<sprite>', {id: 'pf_tiled'}).at(1200, 780).depth(0)
                .size(96, 96).hide().appendTo($.world);
            world.sprite(node, {atlas: {files: ['atlas_0.png', 'atlas_1.png'],
                    tile: {width: 1024, height: 1024, columns: 2, rows: 1}},
                columns: 8, rows: 2, directions: 1, cell: {w: 256, h: 512},
                pivot: 'feet', width: 96, height: 96});
            globalThis.__tiled = node;
            return world.info().atlasSprites;
        })()''')
        tiled_info = info(a)
        tiled_states = {e["path"]: e["state"] for e in tiled_info.get("paths") or []}
        check(tiled > 0, "tiled atlas set registered with prefetched tiles")
        check(tiled_states.get("atlas_0.png") == "consumed" and
              tiled_states.get("atlas_1.png") == "consumed",
              "tiled registration consumed both tile prefetches: %s" % tiled_states)

        # Disable stops the worker and rejects new requests.
        check(a.eval("world.atlasAsync(false)") is False, "atlasAsync(false) disables")
        disabled = info(a)
        check(disabled.get("enabled") is False, "info reports disabled")
        check(disabled.get("workers") == 0, "worker thread stopped on disable")
        check(disabled.get("entries") == 0, "disable drops entries")
        check(a.eval("world.atlasPrefetch('atlas_0.png')") == 0,
              "disabled prefetch returns 0")
        check(disabled.get("enabled") is False, "info still works after disable")

        # Dispose: no crash, engine remains usable for a fresh world.
        a.eval("world.dispose()")
        fresh = a.eval(r'''(() => {
            globalThis.world = $.re2dWorld.fromJSON(%s);
            world.backend('gpu');
            world.render({x: 400, y: 1024, h: 48, yaw: 0, pitch: 0, fov: 80, near: 1}, 160, 90);
            return world.info().atlasSprites;
        })()''' % json.dumps(WORLD_JSON))
        check(fresh == 0, "a fresh world works after dispose (worker joined)")
        check(not a.eval("$.debug.errors()"), "no script errors during the prefetch run")

        return {
            "register_ms": register_wall_ms, "static": static_pixels, "moving": moving_pixels,
            "reload": reload_pixels, "static_info": static_info,
            "moving_info": moving_info, "errors": errors,
            "info": after, "requested": ready,
        }


def run_enabled_not_ready():
    """Prefetch enabled, nothing prefetched: registration must fall back."""
    with Agent(game=GAME, seed=21, fixed_dt=1.0 / 60.0) as a:
        if skip_without_re2d(a):
            return None
        a.step(2)
        json.loads(a.eval(WORLD_JS))
        a.eval("world.atlasAsync(true)")
        t0 = time.perf_counter()
        reg = json.loads(a.eval(REGISTER_JS))
        register_wall_ms = (time.perf_counter() - t0) * 1000.0
        a.eval(STATIC_FRAMES_JS)
        pixels = screenshot(a, "enabled_not_ready")
        state = info(a)
        check(state.get("ready") == 0 and state.get("consumed") == 0,
              "nothing was prefetched: registration used the synchronous path")
        return {"register_ms": register_wall_ms, "static": pixels}


def compare(label, left, right):
    check(left == right, "%s: byte-identical (%d bytes)" % (label, len(left or b"")))


def main():
    build_game()
    control = run_control()
    if control is None:
        return 0
    prefetch = run_prefetch()
    if prefetch is None:
        return 0
    not_ready = run_enabled_not_ready()

    compare("static frame control vs prefetch", control["static"], prefetch["static"])
    compare("120 moving-camera frames control vs prefetch",
            control["moving"], prefetch["moving"])
    compare("hot-reload frame control vs prefetch", control["static"], prefetch["reload"])
    if not_ready:
        compare("enabled-but-not-ready fallback frame",
                control["static"], not_ready["static"])
        check(not_ready["register_ms"] >= 0, "fallback registration time measured")

    for key in ("gpuDraws", "visibleAtlasSprites", "atlasSprites", "gpuDrawsActor"):
        check(control["static_info"].get(key) == prefetch["static_info"].get(key),
              "static frame counter %s matches: %s vs %s"
              % (key, control["static_info"].get(key), prefetch["static_info"].get(key)))
    for key in ("gpuDraws", "visibleAtlasSprites", "atlasSprites"):
        check(control["moving_info"].get(key) == prefetch["moving_info"].get(key),
              "moving frame counter %s matches: %s vs %s"
              % (key, control["moving_info"].get(key), prefetch["moving_info"].get(key)))

    for key in ("missing", "corrupt"):
        check(control["errors"][key] == prefetch["errors"][key],
              "%s file: same typed error with/without prefetch: %r"
              % (key, prefetch["errors"][key]))
        check("no-error" not in prefetch["errors"][key],
              "%s file is rejected, not silently accepted" % key)

    # Honest saving: same PNG decode on both sides; only the sync file read is
    # avoided. Report totals, not a per-frame claim.
    saved_ms = control["register_ms"] - prefetch["register_ms"]
    bytes_read = (prefetch.get("info") or {}).get("bytesRead", 0)
    worker_read_ms = (prefetch.get("info") or {}).get("readMs", 0.0)
    print()
    print("  registration (8 sprites, 8 distinct 1024x1024 PNGs):")
    print("    control (sync reads) : %.2f ms wall around registration" % control["register_ms"])
    print("    prefetch (ready)     : %.2f ms wall around registration" % prefetch["register_ms"])
    print("    wall delta           : %.2f ms (includes IPC/decode; decode unchanged)" % saved_ms)
    print("    worker read time     : %.2f ms (synchronous file-read cost avoided)" % worker_read_ms)
    print("    bytes read by worker : %d" % bytes_read)
    check(saved_ms >= -5.0,
          "prefetch did not make registration measurably slower")
    check(bytes_read > 0, "the worker actually read the PNG bytes: %d" % bytes_read)
    check(worker_read_ms > 0.0,
          "worker read time measured (honest avoided-sync-read number): %.2f ms"
          % worker_read_ms)

    print()
    if FAILED:
        print("ПРОВАЛОВ:", len(FAILED))
        for item in FAILED:
            print("  -", item)
        return 1
    print("Все проверки пройдены")
    return 0


if __name__ == "__main__":
    sys.exit(main())
