// ===========================================================================
// Юнит-тест попаданий по частицам без движка (qjs).
//
// Частица — не тело Box2D, попадание считается здесь: точка против круга и
// отрезок против круга. Ошибка в знаке или в границах t делала бы «выстрел по
// облаку» то промахом, то попаданием в бесконечность.
//
// Запуск:
//   build/_deps/quickjs-build/qjs tests/js/particle_hit_test.mjs
// ===========================================================================

import { test, eq, near, truthy, falsy, finish } from './_harness.mjs';
import { pointInCircle, segmentCircle } from '../../src/highlevel/particles.js';

test('точка внутри круга — попадание, снаружи — нет', () => {
    truthy(pointInCircle(0, 0, 0, 0, 10), 'центр');
    truthy(pointInCircle(10, 0, 0, 0, 10), 'ровно на границе');
    falsy(pointInCircle(10.001, 0, 0, 0, 10), 'чуть снаружи');
    truthy(pointInCircle(5, 5, 4, 4, 2), 'маленький круг');
});

test('отрезок через круг: доля пути до входа', () => {
    const t = segmentCircle(0, 0, 100, 0, 50, 0, 10);
    near(t, 0.4, 1e-6, 'вход в круг на 40 % пути');
});

test('отрезок мимо круга — null', () => {
    eq(segmentCircle(0, 0, 100, 0, 50, 40, 10), null);
    eq(segmentCircle(0, 0, 100, 0, 200, 0, 10), null, 'круг за концом отрезка');
    eq(segmentCircle(0, 0, 100, 0, -50, 0, 10), null, 'круг до начала отрезка');
});

test('начало внутри круга — это 0, а не точка выхода', () => {
    const t = segmentCircle(50, 0, 100, 0, 50, 0, 10);
    eq(t, 0);
});

test('нулевой отрезок: точка внутри — 0, снаружи — null', () => {
    eq(segmentCircle(5, 0, 5, 0, 5, 0, 10), 0);
    eq(segmentCircle(50, 0, 50, 0, 5, 0, 10), null);
});

test('касание границы круга засчитывается', () => {
    const t = segmentCircle(0, 10, 100, 10, 50, 0, 10);
    near(t, 0.5, 1e-6, 'касание по касательной');
});

finish();
