// ===========================================================================
// Юнит-тест коллизий по габариту агента (qjs).
//
// Сетка тайлов помечает клетки, а не объём: «пролезу ли я сюда телом 28×40»
// решается пересечением прямоугольника агента с твёрдыми клетками. Здесь
// проверяется ровно эта арифметика — границы клеток, касания, вырожденный
// габарит. Ошибка на единицу превращала бы проходимый проём в стену.
//
// Запуск:
//   build/_deps/quickjs-build/qjs tests/js/tilemap_agent_test.mjs
// ===========================================================================

import { test, eq, near, truthy, falsy, finish } from './_harness.mjs';
import { cellRange, boxBlocked } from '../../src/highlevel/tilemap.js';

const layer = { tile: 32 };

test('отрезок внутри одной клетки', () => {
    eq(cellRange(5, 20, 0, 32).join(','), '0,0');
});

test('отрезок через несколько клеток', () => {
    eq(cellRange(0, 80, 0, 32).join(','), '0,2');
    eq(cellRange(40, 200, 0, 32).join(','), '1,6');
});

test('касание границы соседнюю клетку не задевает', () => {
    // [0, 32) — ровно первая клетка: вторая начинается на 32 и не задета.
    eq(cellRange(0, 32, 0, 32).join(','), '0,0');
    eq(cellRange(32, 64, 0, 32).join(','), '1,1');
});

test('точка ровно на границе попадает в правую клетку', () => {
    eq(cellRange(32, 32, 0, 32).join(','), '1,1');
    eq(cellRange(0, 0, 0, 32).join(','), '0,0');
});

test('начало сетки не обязано быть нулём', () => {
    eq(cellRange(100, 100, 100, 32).join(','), '0,0');
    eq(cellRange(100, 160, 100, 32).join(','), '0,1');
});

test('нулевой шаг — клеток нет', () => {
    eq(cellRange(0, 10, 0, 0), null);
});

test('пустая карта: агент помещается где угодно', () => {
    const free = () => false;
    falsy(boxBlocked(layer, free, 0, 0, 100, 100, 14, 20));
});

test('габарит задевает твёрдую клетку', () => {
    // Твёрдая клетка (2, 2) занимает x 64..96, y 64..96.
    const solid = (tx, ty) => tx === 2 && ty === 2;
    truthy(boxBlocked(layer, solid, 0, 0, 80, 80, 14, 20), 'центр внутри клетки');
    truthy(boxBlocked(layer, solid, 0, 0, 55, 80, 14, 20), 'задел левым краем');
    falsy(boxBlocked(layer, solid, 0, 0, 49, 80, 14, 20), 'остановился вплотную');
});

test('узкий агент проходит там, где широкий не проходит', () => {
    // Проём: твёрдые клетки (1, 1) и (1, 3), свободна (1, 2) → y 32..64.
    const solid = (tx, ty) => tx === 1 && (ty === 1 || ty === 3);
    const cx = 48, cy = 80;                    // центр свободной клетки (1, 2)
    falsy(boxBlocked(layer, solid, 0, 0, cx, cy, 12, 15), 'габарит 24×30 влезает');
    truthy(boxBlocked(layer, solid, 0, 0, cx, cy, 12, 17), 'габарит 24×34 не влезает');
});

test('карта со сдвигом: left/top учитываются', () => {
    const solid = (tx, ty) => tx === 0 && ty === 0;
    // Карта начинается в (200, 300); клетка (0,0) — мировые 200..232, 300..332.
    truthy(boxBlocked(layer, solid, 200, 300, 210, 310, 5, 5));
    falsy(boxBlocked(layer, solid, 200, 300, 180, 310, 5, 5));
});

finish();
